import {test,expect} from '@playwright/test';
test('accounts, real coordinate reports, verification rules and responsive UI',async({page})=>{
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5173');await page.getByRole('button',{name:'Navigate',exact:true}).click();
 await expect(page.getByRole('heading',{name:'A safer way forward.'})).toBeVisible();
 await page.getByRole('button',{name:'Sign in',exact:true}).first().click();
 await page.getByRole('button',{name:'New here? Create an account'}).click();
 await page.getByLabel('Name',{exact:true}).fill('Browser Tester');
 await page.getByLabel('Email',{exact:true}).fill(`browser-${Date.now()}@example.com`);
 await page.getByLabel('Password',{exact:true}).fill('test-password-123');
 await page.getByRole('button',{name:'Create account',exact:true}).click();
 await expect(page.locator('.modal-overlay')).toHaveCount(0);
 await expect(page.getByText('Realtime community connected',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'Road alerts',exact:false}).first().click();
 await page.getByRole('button',{name:'Report a hazard',exact:true}).last().click();
 await page.getByLabel('Road or landmark').fill('Automated test road');
 await page.getByLabel('Latitude',{exact:true}).fill('10.7867');
 await page.getByLabel('Longitude',{exact:true}).fill('76.6548');
 await page.getByRole('button',{name:'Share report'}).click();
 await expect(page.getByText('Automated test road',{exact:true})).toBeVisible();
 const row=page.locator('.report-row').filter({hasText:'Automated test road'});
 await row.getByRole('button',{name:'Confirm',exact:true}).click();
 await expect(page.locator('.toast')).toContainText('cannot confirm your own');
 await row.getByRole('button',{name:'Cleared',exact:true}).click();
 await expect(page.getByText('Automated test road',{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'Navigate',exact:true}).click();
 await expect(page.locator('.leaflet-container')).toBeVisible();
 await expect(page.locator('.toast')).toHaveCount(0,{timeout:10000});
 await page.waitForFunction(()=>[...document.querySelectorAll('img.leaflet-tile')].filter(i=>i.complete&&i.naturalWidth>0).length>=6,{},{timeout:15000});
 await page.screenshot({path:'docs/browser-desktop.png',fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.screenshot({path:'docs/browser-phone.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();
 expect(errors).toEqual([]);
});
test('live geocoding and road routing with a browser GPS fixture',async({browser})=>{
 const context=await browser.newContext({geolocation:{latitude:10.7867,longitude:76.6548,accuracy:10},permissions:['geolocation']});
 const page=await context.newPage();await page.goto('http://localhost:5173');await page.getByRole('button',{name:'Navigate',exact:true}).click();
 await page.getByRole('button',{name:'Use GPS',exact:true}).click();
 await expect(page.getByText('Your GPS location',{exact:true})).toBeVisible();
 await page.locator('.place-search input').fill('Palakkad Fort, Kerala');
 await page.locator('.place-search button').click();
 await expect(page.locator('.search-results button').first()).toBeVisible({timeout:40000});
 await page.locator('.search-results button').first().click();
 await page.getByRole('button',{name:'Find routes',exact:true}).click();
 await expect(page.locator('.route-card').first()).toBeVisible({timeout:40000});
 await expect(page.locator('.route-caption')).toContainText('OSRM');
 await expect(page.locator('.route-card').first()).toContainText('km');
 await page.screenshot({path:'docs/live-route.png',fullPage:true});await context.close();
});
