import{test,expect}from'@playwright/test';
test('classroom demo: movement, voice-warning scenario, confirmation, closure, detour and reset without GPS or report writes',async({page})=>{
 const writes=[];const errors=[];page.on('request',r=>{if(r.method()==='POST'&&/\/api\/(hazards|routes|alerts|detect)/.test(r.url()))writes.push(r.url())});page.on('pageerror',e=>errors.push(e.message));
 await page.goto('http://localhost:5173');await page.getByRole('button',{name:'Presentation',exact:true}).click();await expect(page.getByRole('heading',{name:'Your classroom. The open road.'})).toBeVisible();
 await page.getByRole('button',{name:'Voice on',exact:true}).click();
 await page.getByRole('button',{name:'Play presentation',exact:true}).click();
 await expect(page.getByText('Virtual vehicle moving',{exact:true})).toBeVisible();
 await expect.poll(()=>page.locator('.virtual-status small').textContent()).not.toMatch(/^0 m travelled/);
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.getByRole('button',{name:'Next scene',exact:true}).click();
 await expect(page.locator('.scenario-banner')).toContainText('Pothole reported 300');
 await page.getByRole('button',{name:'Simulate community confirmation',exact:true}).click();
 await expect(page.locator('.presentation-checklist .done')).toHaveCount(3);
 await page.getByRole('button',{name:'Next scene',exact:true}).click();
 await expect(page.getByRole('button',{name:'Show prepared detour'})).toBeVisible();
 await expect(page.locator('.scenario-banner')).toContainText('Sample flood closure');
 await page.getByRole('button',{name:'Show prepared detour'}).click();
 await expect(page.locator('.scene-label')).toContainText('PREPARED DETOUR');
 await page.getByRole('button',{name:'Pause',exact:true}).click();
 await page.screenshot({path:'docs/presentation-desktop.png',fullPage:true});
 await page.getByRole('button',{name:'Next scene',exact:true}).click();
 await expect(page.locator('.complete-box')).toBeVisible();
 await expect(page.locator('.presentation-checklist .done')).toHaveCount(5);
 await page.getByRole('button',{name:'Reset',exact:true}).click();
 await expect(page.getByRole('button',{name:'Play presentation',exact:true})).toBeVisible();
 await expect(page.locator('.presentation-checklist .done')).toHaveCount(0);
 await page.setViewportSize({width:390,height:844});await page.screenshot({path:'docs/presentation-phone.png',fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy();expect(writes).toEqual([]);expect(errors).toEqual([]);
});
